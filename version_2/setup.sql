-- ==========================================
-- AIFAQ PRO - VERSION 2 ENVIRONMENT SETUP
-- Database: VERSION2_DB
-- ==========================================

-- 1. Create Permanent Environment
CREATE DATABASE IF NOT EXISTS VERSION2_DB;
CREATE SCHEMA IF NOT EXISTS VERSION2_DB.APP_SCHEMA;
USE SCHEMA VERSION2_DB.APP_SCHEMA;

-- 2. Storage & Stages
CREATE OR REPLACE STAGE DOC_STAGE 
    ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE') 
    DIRECTORY = (ENABLE = TRUE);

-- ==========================================
-- 3. Core Tables (From Python App Schema)
-- ==========================================

-- User-Team Mapping
CREATE TABLE IF NOT EXISTS APP_USER_TEAMS (
    USERNAME VARCHAR,
    TEAM_NAME VARCHAR,
    UPDATED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Role Access Mapping (Team -> Category permissions)
CREATE TABLE IF NOT EXISTS ROLE_ACCESS_MAPPING (
    ROLE_NAME VARCHAR,
    ALLOWED_CATEGORY VARCHAR,
    CREATED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Admin Users
CREATE TABLE IF NOT EXISTS ADMIN_USERS (
    USERNAME VARCHAR PRIMARY KEY,
    GRANTED_BY VARCHAR,
    GRANTED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Teams
CREATE TABLE IF NOT EXISTS TEAMS (
    TEAM_NAME VARCHAR PRIMARY KEY,
    DESCRIPTION VARCHAR,
    CREATED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Chat Sessions
CREATE TABLE IF NOT EXISTS CHAT_SESSIONS (
    SESSION_ID VARCHAR PRIMARY KEY,
    USERNAME VARCHAR,
    TITLE VARCHAR,
    CREATED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Chat Messages
CREATE TABLE IF NOT EXISTS CHAT_MESSAGES (
    MESSAGE_ID VARCHAR PRIMARY KEY,
    SESSION_ID VARCHAR,
    ROLE VARCHAR,
    CONTENT VARCHAR,
    SOURCES VARCHAR,
    CREATED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Documents
CREATE TABLE IF NOT EXISTS DOCUMENTS (
    DOC_ID VARCHAR PRIMARY KEY,
    FILENAME VARCHAR,
    CATEGORY VARCHAR,
    UPLOADED_BY VARCHAR,
    UPLOAD_TS TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Chunks (with Vector embeddings)
CREATE TABLE IF NOT EXISTS CHUNKS (
    CHUNK_ID VARCHAR PRIMARY KEY,
    DOC_ID VARCHAR,
    CHUNK_TEXT VARCHAR,
    CHUNK_VEC VECTOR(FLOAT, 768),
    FOREIGN KEY (DOC_ID) REFERENCES DOCUMENTS(DOC_ID)
);

-- Application Categories
CREATE TABLE IF NOT EXISTS APP_CATEGORIES (
    CATEGORY_NAME VARCHAR PRIMARY KEY,
    DESCRIPTION VARCHAR,
    CREATED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Legacy Chat History (for compatibility)
CREATE TABLE IF NOT EXISTS CHAT_HISTORY (
    SESSION_ID VARCHAR,
    USER_ROLE VARCHAR,
    QUERY_TEXT VARCHAR,
    RESPONSE_TEXT VARCHAR,
    TIMESTAMP TIMESTAMP_LTZ
);

-- ==========================================
-- 4. SECURITY POLICY (Row-Level Security)
-- ==========================================
-- Logic: Admins see ALL. Users see only what is mapped in ROLE_ACCESS_MAPPING.

CREATE OR REPLACE ROW ACCESS POLICY VERSION2_RBAC_POLICY 
AS (doc_category VARCHAR) RETURNS BOOLEAN ->
    -- Super Admins bypass checks
    CURRENT_ROLE() IN ('ACCOUNTADMIN', 'SYSADMIN', 'SECURITYADMIN')
    OR
    -- Regular users check the mapping table
    EXISTS (
        SELECT 1 FROM ROLE_ACCESS_MAPPING 
        WHERE ROLE_NAME = CURRENT_ROLE() 
        AND ALLOWED_CATEGORY = doc_category
    );

-- ==========================================
-- 5. SECURE VIEWS
-- ==========================================
-- Ensures the Python app can see Filenames AND respects the policy

CREATE OR REPLACE VIEW SECURE_CHUNKS_VIEW AS 
SELECT 
    c.CHUNK_ID,
    c.DOC_ID,
    c.CHUNK_TEXT,
    c.CHUNK_VEC,
    d.FILENAME,
    d.CATEGORY
FROM CHUNKS c
JOIN DOCUMENTS d ON c.DOC_ID = d.DOC_ID;

