-- ==========================================
-- 7. Apply Row Access Policy to Documents
-- ==========================================
USE SCHEMA VERSION2_DB.APP_SCHEMA;

-- Remove ANY existing policy (prevents the "already has policy" error)
ALTER TABLE DOCUMENTS DROP ALL ROW ACCESS POLICIES;

-- Attach the correct policy
ALTER TABLE DOCUMENTS 
ADD ROW ACCESS POLICY VERSION2_RBAC_POLICY ON (CATEGORY);

